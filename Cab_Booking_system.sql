-- Analysis using Sub queries
    
-- 1)Find the customers whose total spending on completed trips is greater than the average spending of all customers.

select c.CustomerID,c.CustomerName,sum(t.Fare) AS Total_Spending
from customer_details c
join booking_details b 
on c.CustomerID = b.CustomerID
join trip_details t 
on b.BookingID = t.BookingID
where b.status = 'Completed'
group by c.CustomerID, c.CustomerName
having 
sum(t.Fare) > 
(select avg(TotalSpend)
from (
	select sum(t2.Fare) AS TotalSpend
	from booking_details b2
	join trip_details t2 ON b2.BookingID = t2.BookingID
	where b2.status = 'Completed'
	group by b2.CustomerID) AS CustomerSpending
);
-- Amit Patil & Shital Pabale customers whose total spending on completed trips is greater than the average spending of all customers.

-- 2)Drivers who completed more trips than the Average

select d.DriverID,d.DriverName,count(t.TripID) as Total_Trips
